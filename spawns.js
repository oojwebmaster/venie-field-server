export function terrainFingerprint(CONFIG) {
  const T = CONFIG.world.terrain;
  const S = T.sea || {};
  const N = CONFIG.world.pond || {};
  const parts = [
    T.seed, T.worldHalf, T.landRadius, T.boundRadius, T.baseFreq, T.baseAmp,
    T.hillFreq, T.hillAmp, T.ridgeMaskFreq, T.ridgeFreq, T.ridgeAmp, T.ridgePow,
    T.ridgeBias, T.ridgeRound, T.cliffMaskFreq, T.cliffStep, T.detailFreq,
    T.detailAmp, T.tile, T.wallHeight, T.wallWidth,
    S.enabled ? 1 : 0, S.dirDeg, S.arcDeg, S.level, S.shoreRadius,
    S.wiggle, S.wiggleFreq, S.sandSlope, S.shelfSlope, S.coastBlend,
    N.enabled ? 1 : 0, N.center && N.center[0], N.center && N.center[1], N.radius, N.outerU,
  ];
  let h = 2166136261 >>> 0;
  for (let k = 0; k < parts.length; k++) {
    const s = String(parts[k]);
    for (let i = 0; i < s.length; i++) h = Math.imul(h ^ s.charCodeAt(i), 16777619) >>> 0;
    h = Math.imul(h ^ 0x9e3779b9, 16777619) >>> 0;
  }
  return h.toString(36);
}

