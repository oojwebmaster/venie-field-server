/**
 * VENIE FIELD — 아이템 규칙 (게임과 서버가 나눠 갖는 숫자들)
 * ============================================================================
 *
 * ★ src/items.js 와 server/items.js 는 **완전히 같은 파일**이어야 합니다.
 *   게임은 FTP로 카페24에, 서버는 GitHub로 Render에 올라가 파일을 공유할 수
 *   없어서 두 벌을 둡니다. (palette.js·spawns.js·shells.js·badwords.js와
 *   같은 이유이고 `test/wire_test.mjs`가 바이트 단위로 비교합니다)
 *
 * ## 왜 이 파일이 따로 있는가 — `config.js`를 서버가 못 읽습니다
 *
 * 튜닝 값은 원래 전부 `src/config.js`에 있습니다. 그런데 그 파일은 첫 줄부터
 * `navigator.userAgent`를 읽습니다(모바일 판정). 브라우저에만 있는 물건이라
 * Node에서 `import`하면 그 자리에서 터집니다. 그래서 서버는 config를 볼 수
 * 없었고, 같은 숫자를 **환경변수로 한 번 더** 적어 넣고 있었습니다.
 *
 *     src/config.js  world.paint.count = 14
 *     Render 환경변수 ITEM_COUNT       = 14      ← 손으로 맞춰야 했음
 *
 * 이 방식의 진짜 문제는 번거로움이 아니라 **어긋나도 아무 말이 없다**는
 * 것입니다. 서버는 자기 값대로 14개를 띄우고 게임은 자기 값대로 그리므로,
 * 숫자가 달라도 오류가 나지 않습니다. 화면을 한참 보고 세어 봐야 압니다.
 *
 * 그래서 **양쪽이 다 읽을 수 있는 숫자만** 여기로 옮겼습니다. 이 파일은
 * 아무것도 import 하지 않고 브라우저 API도 건드리지 않으므로 어디서든 돕니다.
 * 이제 값을 고칠 곳은 **여기 한 군데**이고, 파일을 양쪽에 올리면 끝입니다.
 *
 * ## 그럼 환경변수는 언제 쓰는가
 *
 * **코드에 적으면 안 되는 것**만 남겼습니다.
 *   · `ADMIN_KEY`, `SCORE_STORE_TOKEN`  — 비밀이라 저장소에 올리면 안 됩니다
 *   · `ALLOW_ORIGIN`, `PORT`            — 배포 환경마다 다릅니다
 * 게임 규칙(개수·확률·점수)은 비밀도 아니고 환경마다 다르지도 않으므로
 * 환경변수에 둘 이유가 없습니다.
 */

